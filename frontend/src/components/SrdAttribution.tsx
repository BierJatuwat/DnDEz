"use client";

/**
 * ข้อความแสดงที่มาของเนื้อหา SRD 5.2.1 — **เงื่อนไขของสัญญาอนุญาต CC-BY-4.0 ไม่ใช่ของประดับ**
 *
 * หน้าไหนที่แสดงเนื้อหาจากคลัง SRD (มอนสเตอร์ เวท สถานะ กฎ) ต้องมีอันนี้อยู่ในหน้าเดียวกัน
 *
 * **ข้อความมาจาก server เสมอ** (`attribution` ที่ติดมากับทุก response ของ `/srd/*`) — ไม่เก็บสำเนาไว้ที่นี่
 * เพราะถ้อยคำถูกบังคับโดยสัญญาอนุญาต การมีสองสำเนาแปลว่าวันหนึ่งจะไม่ตรงกัน และฝั่งที่ผิดคือฝั่งที่ผู้ใช้เห็น
 * · ยังไม่ได้ข้อความ = ยังไม่แสดงอะไรเลย (ดีกว่าแสดงข้อความที่เราแต่งเอง)
 *
 * ต้นฉบับไม่อนุญาตให้ใส่การอ้างอิงถึง Wizards รูปแบบอื่นนอกจากข้อความนี้ — ห้ามเติมโลโก้/ชื่อแบรนด์รอบ ๆ
 */
export function SrdAttribution({ text }: { text: string | null }) {
  if (!text) return null;

  return (
    <p className="text-[11px] leading-relaxed opacity-50 border-t border-black/10 dark:border-white/10 pt-2">
      {text}
    </p>
  );
}
